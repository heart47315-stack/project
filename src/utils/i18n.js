export function normalizeLanguage(language) {
  return AVAILABLE_LANGUAGES.includes(language) ? language : DEFAULT_LANGUAGE;
}

export function getLanguageText(language, key, fallback = '') {
  const normalized = normalizeLanguage(language);
  return translations[normalized]?.[key] ?? translations[DEFAULT_LANGUAGE]?.[key] ?? fallback;
}

export function getLanguageLabel(language) {
  return normalizeLanguage(language) === 'en' ? 'English' : 'ไทย';
}
